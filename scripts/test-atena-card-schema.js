"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const schema = require("../app/atena-card-schema");
assert.equal(schema.version, "atena-card-schema-v7");
assert.equal(schema.widgetContracts.length, schema.canonicalTemplates.length, "Vsak odobren widget mora imeti strojni selection contract.");
assert.ok(schema.widgetContracts.every((widget) => widget.validation && widget.responsive && widget.nativeTheme && widget.persistence));
assert.equal(schema.evaluateWidget("sprememba-in-potrditev", { scope:"module", semanticTags:["sprememba","potrditev"] }).code, "ELIGIBLE", "Odobreni widget 62 mora prestati ustrezen produkcijski selection.");
assert.equal(schema.canonicalTemplates.length, 62, "Aktivna aplikacija mora poznati vseh 62 zasnov iz registra NAZORJEVA.");
assert.deepEqual(schema.canonicalTemplateIds, require("../app/atena-card-templates").approvedTemplateIds);
assert.deepEqual(schema.flows, ["ponudba", "narocnina", "pogajanje", "ponudbe", "klic"]);
assert.equal(schema.catalog.length, 89, "shema mora pokriti vseh 89 obstoječih modulov");
assert.equal(schema.controlContracts.length, 181);
assert.equal(schema.optionContracts.length, 107);
assert.equal(schema.relationContracts.length, 5);
assert.equal(schema.idValidation.ok, true);
assert.equal(schema.idValidation.total, 585);
assert.equal(new Set(schema.catalog.map((card) => card.id)).size, 89);
assert.ok(schema.catalog.every((card) => card.question && card.ariaLabel && card.layoutHint));
assert.ok(schema.catalog.every((card) => card.eventMapping.action === "open-existing-area"));
const reaktivneKartice = schema.catalog.filter((card) => card.stateMapping.storage === "reactive-draft");
assert.deepEqual(reaktivneKartice.map((card) => card.id), ["ponudba:4009"]);
assert.equal(reaktivneKartice[0].kombinacijaId, "pogodbe-stej-ponovi-sestej");
assert.equal(reaktivneKartice[0].fields.find((field) => field.id === 5101).context.persistence.storage, "reactive-draft");
assert.equal(reaktivneKartice[0].fields.find((field) => field.id === 5102).context.persistence.storage, "existing-draft");
const ponudba = schema.detectRelevantCards("Skrbi me cena z DDV in možnost odpovedi.", "ponudba", 6);
assert.ok(ponudba.some((card) => card.areaCode === "cena"));
assert.ok(ponudba.some((card) => card.areaCode === "pogodba"));
const narocnina = schema.relevantAreas("Mesečna cena se je zvišala in naročnino želim odpovedati.", "narocnina", 3);
assert.ok(narocnina.length > 0 && narocnina.length <= 3);
assert.ok(narocnina.some((area) => /stro|cen|odpoved|traj/i.test(area.label)));
assert.deepEqual(schema.toggleChoice([], "da", false), ["da"]);
assert.deepEqual(schema.toggleChoice(["da"], "da", false), []);
assert.deepEqual(schema.toggleChoice(["a"], "b", true), ["a", "b"]);
assert.ok(schema.catalog.some((card) => card.hasOther && card.followUps[0].when === "other"));
assert.deepEqual(schema.matrixReport(), { modules:89, fields:141, reviewedModules:89, reviewedFields:141, missingModules:[], missingFields:[], canonicalTemplates:62, approvedTemplates:62, missingTemplateBindings:[] });
assert.ok(schema.catalog.every((card) => card.ui && card.ui.reason));
assert.ok(schema.catalog.flatMap((card) => card.fields).every((field) => field.ui && field.ui.interaction && field.ui.reason));
assert.ok(schema.catalog.flatMap((card) => card.fields).every((field) => field.ui.selection && field.ui.selection.templateId === field.ui.templateId && field.ui.selection.changed === false), "Matrika 140 polj mora ohraniti semantično varne preslikave.");
assert.ok(schema.catalog.flatMap((card) => card.fields).every((field) => schema.canonicalTemplateIds.includes(field.ui.templateId)), "Vsako od 140 polj mora kazati na potrjeno zasnovo.");
assert.ok(schema.catalog.every((card) => card.templateIds.every((id) => schema.canonicalTemplateIds.includes(id))));
assert.equal(schema.getCard("ponudba", 4006).fields[0].ui.interaction, "quantity-unit");
assert.equal(schema.getCard("ponudbe", 6307).fields[0].ui.interaction, "money");
assert.equal(schema.getCard("narocnina", 6115).fields[0].ui.interaction, "document-upload");
const root = path.join(__dirname, "..");
const html = fs.readFileSync(path.join(root, "app/svetovalec-preverba.html"), "utf8");
const ui = fs.readFileSync(path.join(root, "app/svetovalec-preverba.js"), "utf8");
assert.ok(html.indexOf("atena-card-schema.js") < html.indexOf("svetovalec-preverba.js"));
assert.ok(html.indexOf("atena-card-renderer.js") < html.indexOf("svetovalec-preverba.js"));
assert.ok(html.indexOf("atena-card-templates.js") < html.indexOf("atena-card-schema.js"));
assert.ok(html.indexOf("atena-widget-contract.js") < html.indexOf("atena-card-schema.js"));
// Cache oznaka se po CLAUDE.md obvezno spremeni ob vsaki spremembi CSS,
// zato preverjamo, da obstaja, ne pa njene točne vrednosti.
assert.match(html, /atena-card-templates\.css\?v=[0-9a-z-]+/);
assert.match(html, /data-atena-predlogi[^>]*hidden/);
assert.match(html, /data-atena-rocno-panel[^>]*hidden/);
assert.match(ui, /atenaCardSchema\.relevantAreas/);
assert.match(ui, /atenaCardRenderer\.renderAreas/);
const rendererSource = fs.readFileSync(path.join(root, "app/atena-card-renderer.js"), "utf8");
const renderer = require("../app/atena-card-renderer");
assert.match(rendererSource, /role", "group"/);
assert.equal(renderer.version, "atena-card-renderer-v10");
assert.match(renderer.moduleIconHtml("S01"), /<svg/);
assert.match(renderer.specialModuleContentHtml({ moduleCode:"A01" }, { completedCount:5, totalModules:27, answerCount:12 }), /Potrjeni moduli[\s\S]*5 od 27[\s\S]*Zbrani odgovori[\s\S]*12/);
assert.match(renderer.specialModuleContentHtml({ moduleCode:"C00" }, {}), /Vrsta ponudnika[\s\S]*Oblika ponudbe[\s\S]*Vir ponudbe/);
const shell = renderer.questionShellHtml({ title:"Cena", question:"Kolikšna je cena?", step:1, total:4, contentHtml:'<input>' });
assert.match(shell, /Dopolnite 1\/4/);
assert.match(shell, /data-nazorjeva-question-card/);
assert.match(shell, /class="[^"]*uj-answer-card/);
assert.match(shell, /data-template-card="besedilni-vnos"/);
assert.match(shell, /data-atena-question-change/);
assert.match(shell, /atena-vprasanje-kartica__vprasanje/);
assert.match(ui, /atenaCardRenderer\.questionShellHtml/);
assert.match(ui, /atenaCardRenderer\.moduleContentHtml/);
assert.match(ui, /atenaCardRenderer\.collectValues/);
assert.match(ui, /atenaCardRenderer\.validate/);
const quantity = renderer.moduleContentHtml(schema.getCard("ponudba", 4006), schema.getCard("ponudba", 4006).fields, { 5103:"12 ur" });
assert.match(quantity, /data-atena-interaction="quantity-unit"/);
assert.match(quantity, /data-atena-template-id="kolicina-in-enota"/);
assert.match(quantity, /data-atena-interface-id="atena:field:ponudba:4006:5103"/);
assert.match(quantity, /data-atena-card-id="atena:card:ponudba:4006"/);
assert.match(quantity, /data-atena-context-version="atena-interface-context-v2"/);
assert.match(quantity, /data-atena-control-ids="atena:control:ponudba:4006:5103:number\|atena:control:ponudba:4006:5103:unit"/);
assert.match(quantity, /data-ponudba-field="5103" value="12 ur"/);
const choices = renderer.moduleContentHtml(schema.getCard("ponudba", 4001), schema.getCard("ponudba", 4001).fields, {});
assert.match(choices, /data-atena-option-id="atena:option:ponudba:4001:5001:/);
console.log("Atena card schema: OK (89 modulov, skupni intent in renderer)");
