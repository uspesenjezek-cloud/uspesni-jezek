"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const contract = require("../app/atena-widget-contract");
const schema = require("../app/atena-card-schema");

assert.equal(contract.version, "atena-widget-contract-v3");
assert.equal(contract.contextVersion, "atena-interface-context-v2");
assert.equal(contract.contracts.length, 62);
assert.equal(new Set(contract.contracts.map((item) => item.id)).size, 62);
assert.ok(contract.contracts.every((item) => item.status === "approved" && item.interfaceId && item.context && item.context.intent && item.context.data && item.context.validation && item.context.ui && item.context.persistence));
assert.ok(contract.contracts.every((item) => item.capability && item.questionBinding && item.context.version === "atena-interface-context-v2"));
assert.equal(contract.lunaManifest.widgets.length, 62);
assert.equal(new Set(contract.contracts.map((item) => item.interfaceId)).size, 62);
assert.equal(contract.evaluate("sprememba-in-potrditev", { scope:"module", semanticTags:["sprememba","potrditev"] }).code, "ELIGIBLE");
assert.equal(contract.evaluate("matrika-tveganja", { scope:"field", interaction:"choice-grid" }).code, "SCOPE_MISMATCH");
assert.equal(contract.evaluate("natancen-znesek", { scope:"field", interaction:"long-text" }).code, "INTERACTION_MISMATCH");
assert.equal(contract.evaluate("matrika-tveganja", { scope:"module", semanticTags:["datum"] }).code, "SEMANTIC_MISMATCH");
assert.equal(contract.evaluate("matrika-tveganja", { scope:"module", semanticTags:["verjetnost","vpliv"] }).code, "ELIGIBLE");
const fields = schema.catalog.flatMap((card) => card.fields);
assert.equal(fields.length, 140);
assert.ok(fields.every((field) => field.ui.selection.templateId === field.ui.templateId && !field.ui.selection.changed));
assert.equal(schema.cardContracts.length, 89);
assert.equal(schema.fieldContracts.length, 140);
assert.equal(new Set(schema.cardContracts.map((item) => item.interfaceId)).size, 89, "Vsaka kartica mora imeti enoličen interfaceId.");
assert.equal(new Set(schema.fieldContracts.map((item) => item.interfaceId)).size, 140, "Vsaka vnosna vrstica mora imeti enoličen interfaceId.");
assert.ok(schema.cardContracts.every((item) => item.identity && item.intent && item.data && item.validation && item.ui && item.persistence && item.source));
assert.ok(schema.fieldContracts.every((item) => item.identity && item.intent && item.canonical && item.validation && item.ui && item.persistence && item.source));
assert.ok(fields.every((field) => field.interfaceId === field.ui.interfaceId && schema.getFieldContract(field.interfaceId) === field.context));
const docs = path.join(__dirname, "..", "docs");
const guide = fs.readFileSync(path.join(docs, "NAZORJEVA-WIDGET-GUIDE.md"), "utf8");
const matrix = fs.readFileSync(path.join(docs, "ATENA-QUESTION-WIDGET-MATRIX.md"), "utf8");
const interfaces = fs.readFileSync(path.join(docs, "ATENA-INTERFACE-CONTEXTS.md"), "utf8");
const engineGuide = fs.readFileSync(path.join(docs, "NAZORJEVA-ENGINE.md"), "utf8");
const lunaManifest = JSON.parse(fs.readFileSync(path.join(docs, "NAZORJEVA-LUNA-MANIFEST.json"), "utf8"));
assert.equal((guide.match(/^### \d+\./gm) || []).length, 62, "Vodnik mora imeti ločen opis vsakega od 62 odobrenih widgetov.");
assert.equal((matrix.match(/^\| `atena:field:/gm) || []).length, 140, "Matrika mora vsebovati vseh 140 interface ID-jev polj.");
assert.equal((interfaces.match(/^## [^\n]+ — `atena:card:/gm) || []).length, 89, "Obširni kontekst mora opisati vseh 89 kartic.");
assert.equal((interfaces.match(/^### [^\n]+ — `atena:field:/gm) || []).length, 140, "Obširni kontekst mora opisati vseh 140 vnosnih vrstic.");
assert.match(engineGuide, /draft → test → iterating → ready_for_approval → approved/);
assert.equal(lunaManifest.widgets.length, 62);
assert.equal(lunaManifest.ponudbaQuestions.counts.questions, 25);
assert.equal(lunaManifest.ponudbaQuestions.counts.fields, 58);
console.log("Atena interface contract: OK (62 widgetov, 89 kartic, 140 vnosnih vrstic)");
