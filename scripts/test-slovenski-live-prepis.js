new DataView(noiseTail.buffer, noiseTail.byteOffset, noiseTail.byteLength).setFloat32(0, 0.08, true);
assert.equal(hasSpeechLikeContent(noiseTail), false, "Enkraten šum ne sme postati izmišljena končna beseda");
const spokenTail = Buffer.alloc(320 * 5 * 4 + 1).subarray(1);
const spokenView = new DataView(spokenTail.buffer, spokenTail.byteOffset, spokenTail.byteLength);
for (let index = 0; index < 320 * 4; index += 1) spokenView.setFloat32(index * 4, 0.02, true);
assert.equal(hasSpeechLikeContent(spokenTail), true, "Kratek dejanski govorni rep se mora prepisati");
