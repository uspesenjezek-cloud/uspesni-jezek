new DataView(voiceUnaligned.buffer, voiceUnaligned.byteOffset, voiceUnaligned.byteLength).setFloat32(0, 0.1, true);
assert.equal(hasAudibleContent(voiceUnaligned), true, "Zvočno aktiven neporavnan PCM mora ostati v čakalnem odseku");
const speechLikeSource = server.match(/function hasSpeechLikeContent\(pcm\) \{[\s\S]*?\n\}/)[0];
const hasSpeechLikeContent = Function(`const FRAME_SAMPLES = 320; ${speechLikeSource}; return hasSpeechLikeContent;`)();
