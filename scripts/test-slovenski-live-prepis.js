assert.doesNotMatch(server, /new Float32Array\(pcm\.buffer, pcm\.byteOffset, sampleCount\)/);
const naturalCutSource = server.match(/function findNaturalCut\(pcm, targetSamples = WINDOW_STEP_SAMPLES\) \{[\s\S]*?\n\}/)[0];
const findNaturalCut = Function(`const SAMPLE_RATE = 16000; const WINDOW_STEP_SAMPLES = SAMPLE_RATE * 3; const WINDOW_EARLY_SAMPLES = Math.round(SAMPLE_RATE * 0.6); const WINDOW_LATE_SAMPLES = Math.round(SAMPLE_RATE * 1.2); const WORD_BOUNDARY_QUIET_FRAMES = 4; const FRAME_SAMPLES = 320; ${naturalCutSource}; return findNaturalCut;`)();
const boundaryPcm = Buffer.alloc(Math.round(16000 * 3.8) * 4);
const boundaryView = new DataView(boundaryPcm.buffer, boundaryPcm.byteOffset, boundaryPcm.byteLength);
for (let index = 0; index < boundaryPcm.length / 4; index += 1) {
  const seconds = index / 16000;
  boundaryView.setFloat32(index * 4, seconds >= 3.02 && seconds <= 3.16 ? 0 : (index % 2 ? 0.02 : -0.02), true);
}
const wordBoundaryCut = findNaturalCut(boundaryPcm);
assert.ok(wordBoundaryCut >= 16000 * 3 && wordBoundaryCut <= 16000 * 3.2, "Rez mora izbrati bližnji premor po koncu besede");
const uninterruptedPcm = Buffer.alloc(Math.round(16000 * 3.2) * 4);
const uninterruptedView = new DataView(uninterruptedPcm.buffer, uninterruptedPcm.byteOffset, uninterruptedPcm.byteLength);
for (let index = 0; index < uninterruptedPcm.length / 4; index += 1) uninterruptedView.setFloat32(index * 4, index % 2 ? 0.02 : -0.02, true);
assert.equal(findNaturalCut(uninterruptedPcm), 0, "Brez besedne meje tok ne sme rezati kar na tretji sekundi");
