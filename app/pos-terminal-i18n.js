  function translateRaw(value) {
    var input = String(value == null ? "" : value);
    if (Object.prototype.hasOwnProperty.call(german, input)) return german[input];
    for (var index = 0; index < patterns.length; index += 1) {
      if (patterns[index][0].test(input)) return input.replace(patterns[index][0], patterns[index][1]);
    }
    return input;
  }

  function translate(value) {
    if (locale !== "de") return String(value == null ? "" : value);
    var input = String(value == null ? "" : value);
    var leading = input.match(/^\s*/)[0];
    var trailing = input.match(/\s*$/)[0];
    var core = input.slice(leading.length, input.length - trailing.length);
    return leading + translateRaw(core) + trailing;
  }

  function translateAttributes(element) {
    ["aria-label", "placeholder", "title"].forEach(function (attribute) {
      if (!element.hasAttribute || !element.hasAttribute(attribute)) return;
      var current = element.getAttribute(attribute);
      var next = translate(current);
      if (next !== current) element.setAttribute(attribute, next);
    });
  }

  function translateTextNode(node) {
    if (!node || node.nodeType !== 3 || !node.nodeValue || !node.nodeValue.trim()) return;
    var next = translate(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
  }

  function translateTree(root) {
    if (locale !== "de" || !root) return;
    if (root.nodeType === 3) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType === 1) translateAttributes(root);
    if (!global.document || !global.document.createTreeWalker) return;
    var walker = global.document.createTreeWalker(root, 5);
    var current;
    while ((current = walker.nextNode())) {
      if (current.nodeType === 1) translateAttributes(current);
      else translateTextNode(current);
    }
  }

  function startBrowserTranslation() {
    if (!global.document) return;
    global.document.documentElement.lang = locale;
    if (locale !== "de") return;
    var observer = new MutationObserver(function (mutations) {
      mutations.forEach(function (mutation) {
        if (mutation.type === "characterData") translateTextNode(mutation.target);
        else if (mutation.type === "attributes") translateAttributes(mutation.target);
        else Array.prototype.forEach.call(mutation.addedNodes || [], translateTree);
      });
    });
    observer.observe(global.document, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: ["aria-label", "placeholder", "title"]
    });
    if (global.document.readyState === "loading") {
      global.document.addEventListener("DOMContentLoaded", function () { translateTree(global.document); }, { once: true });
    } else translateTree(global.document);
  }

