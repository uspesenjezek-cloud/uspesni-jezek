function promptContext(flow) {
  var entries = entriesFor(flow);
  if (!entries.length) return "";
  return [
    "KNOWN LUNA ERROR MEMORY (" + ERROR_KNOWLEDGE_VERSION + ").",
    "Confirmed synthetic negative lessons; generalize the rule, not keywords.",
  ].concat(entries.map(function (entry) {
    return [
      "ERROR " + entry.id + ".",
      entry.promptLesson,
    ].join(" ");
  })).join(" ");
}

